import { randomBytes } from "node:crypto";
import { DEFAULT_TIMEZONE } from "@talorys/shared/constants";

/** Compatibility date for generated Worker and Pages configs. */
export const COMPATIBILITY_DATE = "2026-10-01";

/**
 * Durable Object migrations. Append-only: never edit or remove an entry, or
 * Cloudflare would refuse the deploy (or worse, delete the owner's data).
 * Must match apps/agent/wrangler.jsonc.
 */
export const DO_MIGRATIONS = [{ tag: "v1", new_sqlite_classes: ["TalorysAgent"] }] as const;

export const DO_BINDING = "TalorysAgent";
export const SERVICE_BINDING = "AGENT";

export interface ResourceNames {
  installationId: string;
  workerName: string;
  pagesProjectName: string;
}

const ALPHABET = "abcdefghijklmnopqrstuvwxyz0123456789";

/** A plain hostname with at least two labels: no scheme, port, path or wildcard. */
const HOSTNAME = /^(?=.{1,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z][a-z0-9-]{0,61}[a-z0-9]$/;

/** The custom domain in canonical form, or null for none. Throws on anything but a bare hostname. */
export function normalizeDomain(value: string | undefined | null): string | null {
  const domain = (value ?? "").trim().toLowerCase().replace(/\.$/, "");
  if (!domain) return null;
  if (!HOSTNAME.test(domain)) throw new Error(`Not a valid domain: ${value}`);
  return domain;
}

/** Collision-resistant, DNS-safe installation id (8 chars ≈ 41 bits). */
export function generateInstallationId(bytes = randomBytes(8)): string {
  let id = "";
  for (const b of bytes) id += ALPHABET[b % ALPHABET.length];
  // Must start with a letter for maximum compatibility with naming rules.
  return /^[a-z]/.test(id) ? id : `t${id.slice(1)}`;
}

export function resourceNames(installationId: string): ResourceNames {
  if (!/^[a-z][a-z0-9]{3,15}$/.test(installationId)) throw new Error(`Invalid installation id: ${installationId}`);
  return {
    installationId,
    workerName: `talorys-${installationId}-agent`,
    pagesProjectName: `talorys-${installationId}-web`,
  };
}

export interface AgentConfigInput {
  workerName: string;
  installationId: string;
  version: string;
  timezone: string;
  agentName: string;
  main?: string;
  /** Emits TALORYS_SEMANTIC_DEFAULT "on" so the agent seeds semantic recall once on first boot. */
  semanticDefault?: boolean;
  /** The owner's own domain: the API then answers only there, not on *.pages.dev (DOM-01, AUTH-03). */
  domain?: string | null;
}

/** wrangler.jsonc for the private agent Worker. */
export function generateAgentConfig(input: AgentConfigInput): Record<string, unknown> {
  return {
    $comment: "Generated by create-talorys. Re-run `npx create-talorys@latest update` instead of editing by hand.",
    name: input.workerName,
    main: input.main ?? "worker.js",
    compatibility_date: COMPATIBILITY_DATE,
    compatibility_flags: ["nodejs_compat"],
    // Private backend: no workers.dev URL and no preview URLs. Only the Pages service binding can reach it.
    workers_dev: false,
    preview_urls: false,
    ai: { binding: "AI" },
    durable_objects: { bindings: [{ name: DO_BINDING, class_name: "TalorysAgent" }] },
    migrations: DO_MIGRATIONS,
    vars: {
      TALORYS_INSTALLATION_ID: input.installationId,
      TALORYS_DEPLOYED_VERSION: input.version,
      TALORYS_DEFAULT_TIMEZONE: input.timezone,
      TALORYS_AGENT_NAME: input.agentName,
      // Only a Yes adds a var, so a No install's config matches upstream exactly.
      ...(input.semanticDefault ? { TALORYS_SEMANTIC_DEFAULT: "on" } : {}),
      ...(input.domain ? { TALORYS_ALLOWED_HOSTS: input.domain } : {}),
    },
    observability: { enabled: true },
  };
}

/** wrangler.jsonc for the Pages project (static assets + Functions + service binding). */
export function generatePagesConfig(input: { pagesProjectName: string; workerName: string }): Record<string, unknown> {
  return {
    $comment: "Generated by create-talorys.",
    name: input.pagesProjectName,
    pages_build_output_dir: "./dist",
    compatibility_date: COMPATIBILITY_DATE,
    services: [{ binding: SERVICE_BINDING, service: input.workerName }],
  };
}

export function toJsonc(config: Record<string, unknown>): string {
  const { $comment, ...rest } = config;
  return `${$comment ? `// ${$comment}\n` : ""}${JSON.stringify(rest, null, 2)}\n`;
}

export function detectTimezone(): string {
  try {
    return Intl.DateTimeFormat().resolvedOptions().timeZone || DEFAULT_TIMEZONE;
  } catch {
    return DEFAULT_TIMEZONE;
  }
}
